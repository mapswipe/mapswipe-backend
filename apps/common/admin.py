@admin.register(Announcement)
class AnnouncementAdmin(DjangoQLSearchMixin, FirebaseResourceAdmin, UserResourceAdmin, admin.ModelAdmin):  # type: ignore[reportMissingTypeArgument]
    list_display = ("text", "is_active", "url")

    @typing.override
    def save_model(self, request, obj, form, change):  # type: ignore[reportMissingParameterType]
        super().save_model(request, obj, form, change)

        if obj.is_active:
            previous_announcements = Announcement.objects.exclude(id=obj.id)
            previous_announcements.update(is_active=False)

            FirebaseAnnouncementPush(obj).trigger(force_update=True)
        else:
            FirebaseAnnouncementPush(obj).trigger(delete=True)


class AppReleaseInline(admin.StackedInline[AppRelease, AppInfo]):
    model = AppRelease
    extra = 0


@admin.register(AppInfo)
class AppInfoAdmin(FirebaseResourceAdmin, UserResourceAdmin, admin.ModelAdmin):  # type: ignore[reportMissingTypeArgument]
    list_display = ("platform", "latest_version", "min_supported_version")
    readonly_fields = ("platform",)
    inlines = (AppReleaseInline,)

    @typing.override
    def get_form(self, request, obj=None, change=False, **kwargs):  # type: ignore[reportMissingParameterType]
        form = super().get_form(request, obj, change=change, **kwargs)
        # NOTE: Only the saved releases of this platform can be selected as the latest version
        if "latest_version" in form.base_fields:
            form.base_fields["latest_version"].queryset = (  # type: ignore[reportAttributeAccessIssue]
                obj.releases.all() if obj else AppRelease.objects.none()
            )
        return form

    # NOTE: The rows for each platform are created by the migration
    @typing.override
    def has_add_permission(self, request):  # type: ignore[reportMissingParameterType]
        return False

    @typing.override
    def has_delete_permission(self, request, obj=None):  # type: ignore[reportMissingParameterType]
        # NOTE: Deleting would leave the data on firebase. Update the releases instead.
        return False

    @typing.override
    def save_related(self, request, form, formsets, change):  # type: ignore[reportMissingParameterType]
        # NOTE: Push after the inline releases are saved
        super().save_related(request, form, formsets, change)
        app_info = form.instance
        # NOTE: The latest version could have been removed with the inline releases
        app_info.refresh_from_db()
        FirebaseAppInfoPush(app_info).trigger(force_update=True)
